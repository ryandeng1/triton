"""Regenerate the isolated AITER kernels; does not download or execute GPU code."""

import ast
import difflib
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
VENDOR = ROOT / "vendor" / "aiter"
REVISION = "ef0a5a26b8cb38ea1308f827985e36cde964a6ab"


def main():
    source = (VENDOR / "rmsnorm_upstream.py").read_text()
    lines = source.splitlines(keepends=True)
    functions = {node.name: node for node in ast.parse(source).body if isinstance(node, ast.FunctionDef)}
    original_names = ["_rms_norm_kernel", "_rmsnorm_bwd_triton", "_rmsnorm_bwd_dg_reduce_triton"]
    output = [
        '# SPDX-License-Identifier: MIT\n',
        '# Copyright (C) 2024-2026, Advanced Micro Devices, Inc. All rights reserved.\n',
        '# Extracted and adapted for semantic-contract experiments.\n',
        '# Generated by build_rmsnorm_kernels.py; vendor/aiter contains original source/license.\n',
        'import triton\nimport triton.language as tl\n\n',
    ]
    manifest = {
        "repository": "https://github.com/ROCm/aiter",
        "revision": REVISION,
        "source_path": "aiter/ops/triton/_triton_kernels/normalization/rmsnorm.py",
        "source_sha256": hashlib.sha256(source.encode()).hexdigest(),
        "scope": "Direct persistent kernel calls, USE_BLOCKED=False; not full stock AITER provider dispatch.",
        "extraction_changes": ["Replace repr-dependent decorator with ordinary @triton.jit.", "Rename entry points for isolated comparisons; original function bodies remain unchanged."],
        "hoisting_changes": ["In nonblocked branch only, move gamma load and FP32 conversion outside persistent row loop.", "Conjoin the hoisted load mask with row_start < n_rows to preserve zero-trip memory access behavior."],
        "functions": {},
    }
    source_paths = {
        "rmsnorm_upstream.py": "aiter/ops/triton/_triton_kernels/normalization/rmsnorm.py",
        "rmsnorm_wrapper_upstream.py": "aiter/ops/triton/normalization/rmsnorm.py",
        "LICENSE": "LICENSE",
    }
    manifest["vendored_files"] = {
        name: {"source_url": f"https://github.com/ROCm/aiter/blob/{REVISION}/{path}",
               "sha256": hashlib.sha256((VENDOR / name).read_bytes()).hexdigest()}
        for name, path in source_paths.items()
    }
    patches = []
    for name in original_names:
        node = functions[name]
        body = ''.join(lines[node.lineno - 1:node.end_lineno])
        manifest["functions"][name] = {"upstream_start_line": node.lineno,
                                        "upstream_end_line": node.end_lineno,
                                        "unmodified_function_sha256": hashlib.sha256(body.encode()).hexdigest()}
        if name.endswith("dg_reduce_triton"):
            renamed = body.replace(f"def {name}(", "def rmsnorm_dg_reduce(", 1)
            output.append('@triton.jit\n' + renamed + '\n\n')
            continue
        base = "rmsnorm_forward" if name == "_rms_norm_kernel" else "rmsnorm_backward"
        original = body.replace(f"def {name}(", f"def {base}_original(", 1)
        prefix, suffix = body.rsplit("    else:\n", 1)
        load = "            g = tl.load(g_ptr + col_offsets, mask=mask, other=0.0).to(tl.float32)\n"
        assert suffix.count(load) == 1
        suffix = suffix.replace(load, "", 1)
        invariant = "        g = tl.load(g_ptr + col_offsets, mask=mask & (row_start < n_rows), other=0.0).to(tl.float32)\n"
        loop = "        for row_idx in tl.range("
        assert suffix.count(loop) == 1
        suffix = suffix.replace(loop, invariant + loop, 1)
        hoisted = (prefix + "    else:\n" + suffix).replace(f"def {name}(", f"def {base}_hoisted(", 1)
        output.extend(['@triton.jit\n' + original + '\n\n', '@triton.jit\n' + hoisted + '\n\n'])
        patches.extend(difflib.unified_diff(original.splitlines(keepends=True), hoisted.splitlines(keepends=True), fromfile=base + "_original", tofile=base + "_hoisted"))
    result = ''.join(output)
    extracted = {node.name: node for node in ast.parse(result).body if isinstance(node, ast.FunctionDef)}
    for old, new in [("_rms_norm_kernel", "rmsnorm_forward_original"),
                     ("_rmsnorm_bwd_triton", "rmsnorm_backward_original"),
                     ("_rmsnorm_bwd_dg_reduce_triton", "rmsnorm_dg_reduce")]:
        assert ast.dump(ast.Module(body=functions[old].body, type_ignores=[])) == ast.dump(
            ast.Module(body=extracted[new].body, type_ignores=[])), f"{old} body changed"
    manifest["baseline_bodies_ast_identical"] = True
    (ROOT / "rmsnorm_kernels.py").write_text(result)
    (VENDOR / "hoisting.diff").write_text(''.join(patches))
    manifest["extracted_kernels_sha256"] = hashlib.sha256(result.encode()).hexdigest()
    (VENDOR / "provenance.json").write_text(json.dumps(manifest, indent=2) + '\n')


if __name__ == "__main__":
    main()
